#!/usr/bin/env python3
"""Temporary sound bed for the subtitle-only cut of EP1 (no voices yet).
music_ep1.wav : slow minor pad that changes chord every 8 s, the 'ลูกนกน้อย' music-box lullaby in the memory/clue scenes,
                church bell hits wherever the script calls for the bell.
The wind/room tone is generated by ffmpeg in assemble_ep1.sh and mixed under this.
"""
import json, os, wave
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
TL = json.load(open(os.path.join(HERE, "ep1_timeline.json")))
SR = 48000
TOTAL = TL["total"]
N = int(TOTAL * SR) + SR
out = np.zeros(N, np.float32)

def hz(midi): return 440.0 * 2 ** ((midi - 69) / 12)

# --- pad: Am  F  C  E (low, soft), chords crossfade over 2 s -------------------
CHORDS = [[45, 52, 57, 60], [41, 48, 53, 57], [48, 52, 55, 60], [40, 47, 52, 56]]
STEP, XF = 8.0, 2.0
t_all = np.arange(N, dtype=np.float64) / SR
for ci, chord in enumerate(CHORDS):
    env = np.zeros(N, np.float32)
    k = 0
    while k * STEP < TOTAL + STEP:
        if k % len(CHORDS) == ci:
            a, b = k * STEP - XF / 2, (k + 1) * STEP + XF / 2
            i0, i1 = max(0, int(a * SR)), min(N, int(b * SR))
            if i1 > i0:
                tt = (np.arange(i0, i1) / SR - a) / (b - a)
                env[i0:i1] = np.minimum(1, np.minimum(tt, 1 - tt) / (XF / (b - a)))
        k += 1
    sig = np.zeros(N, np.float32)
    for m in chord:
        f = hz(m)
        sig += (np.sin(2 * np.pi * f * t_all) + .25 * np.sin(2 * np.pi * 2 * f * t_all + .7)).astype(np.float32)
    out += .018 * env * sig * (1 + .25 * np.sin(2 * np.pi * .07 * t_all)).astype(np.float32)
del t_all

# --- music box lullaby (original melody) in memory / clue scenes ----------------
MELODY = [(69, 1), (72, 1), (71, .5), (69, .5), (67, 1), (64, 2), (65, 1), (67, 1), (69, .5), (67, .5), (65, 1), (64, 2),
          (69, 1), (72, 1), (76, 1.5), (74, .5), (72, 1), (71, 1), (69, 3)]
BEAT = .55
def box_note(f, dur=1.6):
    n = int(dur * SR); t = np.arange(n) / SR
    s = np.sin(2 * np.pi * f * t) + .35 * np.sin(2 * np.pi * 4.02 * f * t) * np.exp(-t * 9)
    return (s * np.exp(-t * 2.6)).astype(np.float32)
BOX_STAGES = {"flash_dorm", "dream", "doll", "album", "tag", "question", "steps"}
for seg in TL["segments"]:
    if seg.get("stage") not in BOX_STAGES: continue
    t = seg["t0"] + .4
    end = seg["t0"] + seg["dur"] - .5
    while t < end:
        for m, beats in MELODY:
            if t >= end: break
            note = box_note(hz(m + 12))
            fade = min(1, (end - t) / 1.5)
            i = int(t * SR); out[i:i + len(note)] += .05 * fade * note[:max(0, N - i)]
            t += beats * BEAT
        t += 2 * BEAT

# --- church bell -----------------------------------------------------------------
def bell(dur=7.0, f0=196.0):
    n = int(dur * SR); t = np.arange(n) / SR
    s = np.zeros(n)
    for ratio, amp, dec in [(.5, .6, .35), (1, 1, .55), (1.19, .55, .8), (1.5, .45, .9), (2, .4, 1.2), (2.74, .25, 1.8), (3.76, .15, 2.6)]:
        s += amp * np.sin(2 * np.pi * f0 * ratio * t) * np.exp(-t * dec)
    s *= np.minimum(1, t / .004)
    return (s / 3).astype(np.float32)
B = bell()
for seg in TL["segments"]:
    for b in seg.get("bells", []):
        i = int((seg["t0"] + b) * SR)
        for rep in range(3):          # three slow tolls
            j = i + int(rep * 2.4 * SR)
            if j >= N: break
            out[j:j + len(B)] += .32 * B[:N - j]

# the Rosa clip already has its own candle puff; give it the same timing here
for seg in TL["segments"]:
    if seg["type"] == "video":
        i = int((seg["t0"] + 7.65) * SR); n = int(.35 * SR)
        puff = np.random.default_rng(1).standard_normal(n).astype(np.float32) * np.exp(-np.arange(n) / SR * 9).astype(np.float32)
        out[i:i + n] += .06 * puff

out = np.clip(out, -1, 1)
pcm = (out * 32767).astype(np.int16)
with wave.open(os.path.join(HERE, "music_ep1.wav"), "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())
print(f"music_ep1.wav {TOTAL / 60:.1f} min, peak {np.abs(out).max():.2f}")
